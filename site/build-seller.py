"""Fill seller details (data/seller.json) into the subscription and legal pages.

Elements marked with data-seller="<field>" get the field as their text.
<a data-seller="email"> also gets href="mailto:...", data-seller="phone"
gets href="tel:+...", data-seller="telegram" gets href="https://t.me/...". A field is a string or {"ru": ..., "en": ...}:
the static HTML gets the Russian value, and js/seller.js carries all of
them so the language switcher (js/i18n.js) shows the translated one.
Run after editing data/seller.json; the script fails (exit 1) while a
value is still a placeholder like "[цена]", because the payment
aggregator checks these details on the live site.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGES = ["private.html", "offer.html", "terms.html", "privacy.html", "consent-pd.html", "consent-ads.html", "consent-author.html", "cookies.html"]

ELEMENT = re.compile(r'<(?P<tag>\w+)\b(?P<attrs>[^>]*\bdata-seller="(?P<key>\w+)"[^>]*)>[^<]*</(?P=tag)>')


def href_for(key, value):
    if key == "email":
        return "mailto:" + value
    if key == "phone":
        return "tel:+" + re.sub(r"\D", "", value)
    if key == "telegram":
        return "https://" + value
    return None


def static_value(value):
    """Russian value of a field: the static pages are Russian."""
    if isinstance(value, dict):
        return value.get("ru") or value.get("en") or ""
    return value


def fill(text, seller, page):
    def repl(m):
        key = m["key"]
        if key not in seller:
            raise SystemExit(f"{page}: unknown data-seller field '{key}'")
        value = static_value(seller[key])
        attrs = m["attrs"]
        href = href_for(key, value)
        if href is not None and m["tag"] == "a":
            attrs = re.sub(r'\shref="[^"]*"', "", attrs)
            attrs += f' href="{html.escape(href)}"'
        return f'<{m["tag"]}{attrs}>{html.escape(value, quote=False)}</{m["tag"]}>'
    return ELEMENT.subn(repl, text)


def main():
    seller = json.loads((ROOT / "data" / "seller.json").read_text(encoding="utf-8"))
    public = {k: v for k, v in seller.items() if not k.startswith("_")}
    js = ("/* Generated by build-seller.py from data/seller.json, do not edit. */\n"
          "var SELLER = " + json.dumps(public, ensure_ascii=False, indent=2) + ";\n")
    with (ROOT / "js" / "seller.js").open("w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print("OK  js/seller.js")
    for page in PAGES:
        path = ROOT / page
        with path.open(encoding="utf-8", newline="") as f:
            text = f.read()
        new, count = fill(text, seller, page)
        if count == 0:
            raise SystemExit(f"{page}: no data-seller elements (footer missing?)")
        if new != text:
            with path.open("w", encoding="utf-8", newline="") as f:
                f.write(new)
        print(f"OK  {page}  ({count} fields)")
    pending = [k for k, v in public.items() if "[" in json.dumps(v, ensure_ascii=False)]
    if pending:
        print("NOT READY: fill in data/seller.json: " + ", ".join(pending), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
