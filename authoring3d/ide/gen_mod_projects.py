#!/usr/bin/env python3
"""Generate separate IDE assemblies from the runtime mod manifest boundaries."""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
import json
import os
from pathlib import Path
import re
import sys
import uuid
import xml.etree.ElementTree as ET


MARKER = "Generated by authoring3d/ide/gen_mod_projects.py; rerun ide/update_mod_projects."
PROJECT_TYPE = "{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}"
FOLDER_TYPE = "{2150E333-8FDC-42A3-9474-1A3956D46DE8}"
GUID_NAMESPACE = uuid.UUID("9044debb-e089-47f1-824e-cd62228102a0")


@dataclass
class ModProject:
    """A manifest assembly, or its separately compiled test_sources assembly."""

    id: str
    directory: Path
    group: str
    manifest: dict
    depends: list[str] = field(default_factory=list)
    tests: bool = False
    kind: str = "mod"

    @property
    def path(self) -> Path:
        return self.directory / (self.id + ".csproj")


def read_json(path: Path) -> dict:
    with path.open(encoding="utf-8-sig") as stream:
        return json.load(stream)


def relative(path: Path, start: Path) -> str:
    return os.path.relpath(path, start).replace("\\", "/")


def dependency_id(value: str) -> str:
    match = re.fullmatch(r"([^<>=^?\s]+)(?:[<>=^].+?)?\??", value.strip())
    if not match:
        raise ValueError("Invalid dependency: " + value)
    return match.group(1)


def safe_pattern(value: str) -> str:
    value = value.replace("\\", "/")
    if not value or value.startswith("/") or ":" in value or ";" in value or ".." in value.split("/"):
        raise ValueError("Expected a mod-relative pattern: " + value)
    return "/".join(part for part in value.split("/") if part not in ("", "."))


def source_pattern(value: str) -> str:
    # ModSourceCollector walks subdirectories for BOTH src/*.cs and src/**/*.cs.
    value = safe_pattern(value)
    if value.endswith("/"):
        return value + "**/*.cs"
    if "/" not in value:
        return value + "/**/*.cs"
    directory, suffix = value.rsplit("/", 1)
    while directory == "**" or directory.endswith("/**"):
        directory = directory[:-3] if len(directory) > 2 else ""
    return (directory + "/" if directory else "") + "**/" + suffix


def discover(root: Path) -> dict[str, ModProject]:
    projects = {}
    for group in ("mods", "mods_private"):
        for path in sorted((root / group).glob("*/manifest.json")):
            if path.parent.name.startswith("."):
                continue
            manifest = read_json(path)
            mod_id = manifest.get("id") or path.parent.name
            add_project(projects, ModProject(mod_id, path.parent, group, manifest))
            for kind in ("integrations", "test_suites"):
                for declaration in manifest.get(kind, []):
                    nested_id = mod_id + "__" + declaration["id"]
                    folder = safe_pattern(declaration.get("path") or kind + "/" + declaration["id"])
                    nested_path = path.parent / folder / "manifest.json"
                    nested = read_json(nested_path)
                    implicit = [mod_id]
                    if kind == "integrations":
                        implicit.extend(declaration.get("with", []))
                    add_project(projects, ModProject(nested_id, nested_path.parent, group, nested, implicit, kind=kind))
    for project in list(projects.values()):
        project.depends.extend(dependency_id(value) for value in project.manifest.get("depends", []))
        project.depends = sorted(set(project.depends))
    for project in list(projects.values()):
        if project.manifest.get("test_sources"):
            # ModTestEngine compiles tests against the selected all-mods run, not the production
            # host's dependency closure. Keep that broader test-only view out of production projects.
            visible = test_visibility(projects)
            tests = ModProject(project.id + "__tests", project.directory, project.group, project.manifest,
                               sorted(set([project.id, *project.depends, *visible])), True, "tests")
            add_project(projects, tests)
    validate_graph(projects)
    return projects


def test_visibility(projects: dict[str, ModProject]) -> list[str]:
    visible = {item.id for item in projects.values()
               if item.kind == "mod" and not item.manifest.get("fixture", False)}
    for item in projects.values():
        if item.kind == "integrations" and set(item.depends).issubset(visible):
            visible.add(item.id)
    return sorted(visible)


def add_project(projects: dict[str, ModProject], project: ModProject) -> None:
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", project.id) or project.id in projects:
        raise ValueError("Invalid or duplicate project identity: " + project.id)
    projects[project.id] = project


def reference_scope(project: ModProject, projects: dict[str, ModProject]) -> list[ModProject]:
    pending = [project.id, *project.depends]
    visible = set()
    while pending:
        mod_id = pending.pop()
        if mod_id in visible or mod_id not in projects:
            continue
        visible.add(mod_id)
        pending.extend(projects[mod_id].depends)
    return [projects[mod_id] for mod_id in sorted(visible) if not projects[mod_id].tests]


def validate_graph(projects: dict[str, ModProject]) -> None:
    pending = set(projects)
    while pending:
        ready = set()
        for mod_id in sorted(pending):
            if not pending.intersection(projects[mod_id].depends):
                ready.add(mod_id)
        if not ready:
            raise ValueError("Mod dependency cycle: " + ", ".join(sorted(pending)))
        pending.difference_update(ready)


def property_element(group: ET.Element, name: str, value: str, condition: str | None = None) -> None:
    attributes = {"Condition": condition} if condition else {}
    ET.SubElement(group, name, attributes).text = value


def add_project_reference(group: ET.Element, path: str, condition: str | None = None,
                          additional: str | None = None) -> None:
    attributes = {"Include": path}
    if condition:
        attributes["Condition"] = condition
    element = ET.SubElement(group, "ProjectReference", attributes)
    # These are compile contexts. Copying the core's player reference pack beside every mod
    # would multiply thousands of identical files without improving IDE type resolution.
    ET.SubElement(element, "Private").text = "false"
    if additional:
        ET.SubElement(element, "AdditionalProperties").text = additional


def installed_reference(group: ET.Element, name: str, path: str, condition: str | None = None) -> None:
    attributes = {"Include": name}
    if condition:
        attributes["Condition"] = condition
    reference = ET.SubElement(group, "Reference", attributes)
    ET.SubElement(reference, "HintPath").text = path
    ET.SubElement(reference, "Private").text = "false"


def library_projects(project: ModProject) -> list[Path]:
    if project.tests:
        return []
    return sorted((project.directory / "source_code").glob("*.csproj"))


def source_output_props(project: ModProject, root: Path, directory: Path) -> str:
    xml = ET.Element("Project")
    xml.append(ET.Comment(" " + MARKER + " "))
    props = ET.SubElement(xml, "PropertyGroup")
    property_element(props, "CthangoverRoot", "$(MSBuildThisFileDirectory)" + relative(root, directory) + "/",
                     "'$(CthangoverRoot)' == ''")
    ET.SubElement(xml, "Import", {"Project": "$(CthangoverRoot)Directory.Build.props",
                                 "Condition": "Exists('$(CthangoverRoot)Directory.Build.props')"})
    outputs = ET.SubElement(xml, "PropertyGroup")
    intermediate = "$(CthangoverRoot).ide/obj/source_" + project.id + "/$(MSBuildProjectName)/"
    property_element(outputs, "BaseIntermediateOutputPath", intermediate)
    property_element(outputs, "MSBuildProjectExtensionsPath", intermediate)
    property_element(outputs, "BaseOutputPath", "$(CthangoverRoot).ide/bin/source_" + project.id + "/$(MSBuildProjectName)/")
    property_element(outputs, "DefaultItemExcludes", "$(DefaultItemExcludes);bin/**;obj/**")
    property_element(outputs, "DefaultItemExcludes", "$(DefaultItemExcludes);bin/**;obj/**")
    ET.indent(xml, space="  ")
    return ET.tostring(xml, encoding="unicode") + "\n"


def generate_project(project: ModProject, projects: dict[str, ModProject], root: Path,
                     target_framework: str, language_version: str, godot_version: str) -> str:
    xml = ET.Element("Project")
    xml.append(ET.Comment(" " + MARKER + " "))
    early = ET.SubElement(xml, "PropertyGroup")
    property_element(early, "CthangoverRoot", "$(MSBuildThisFileDirectory)" + relative(root, project.directory) + "/",
                     "'$(CthangoverRoot)' == ''")
    property_element(early, "CthangoverRoot", "$([MSBuild]::EnsureTrailingSlash('$(CthangoverRoot)'))")
    property_element(early, "CthangoverInstalledDirectory", "$(CthangoverRoot)",
                     "'$(CthangoverInstalledDirectory)' == ''")
    property_element(early, "BaseIntermediateOutputPath", "$(CthangoverRoot).ide/obj/" + project.id + "/")
    property_element(early, "MSBuildProjectExtensionsPath", "$(BaseIntermediateOutputPath)")
    property_element(early, "OutputPath", "$(CthangoverRoot).ide/bin/" + project.id + "/$(Configuration)/")
    ET.SubElement(xml, "Import", {"Project": "Sdk.props", "Sdk": "Microsoft.NET.Sdk"})
    props = ET.SubElement(xml, "PropertyGroup")
    values = {
        "TargetFramework": target_framework,
        "LangVersion": language_version,
        "Nullable": "disable",
        "ImplicitUsings": "disable",
        "EnableDefaultItems": "false",
        "EnableDefaultCompileItems": "false",
        "GenerateAssemblyInfo": "false",
        "GenerateTargetFrameworkAttribute": "false",
        "EnableNETAnalyzers": "false",
        "EnableDefaultEmbeddedResourceItems": "false",
        "EnableDefaultNoneItems": "false",
        "DisableImplicitFrameworkDefines": "true",
        "AssemblyName": project.id,
        "RootNamespace": project.id,
        "GodotProjectDir": "$(CthangoverRoot)",
        "GodotProjectDirBase64": "$([MSBuild]::ConvertToBase64('$(GodotProjectDir)'))",
        "GodotDisabledSourceGenerators": "",
    }
    for name, value in values.items():
        property_element(props, name, value)
    compile_items = ET.SubElement(xml, "ItemGroup")
    patterns = project.manifest.get("test_sources" if project.tests else "sources", [])
    exclude = ["test_suites/**", "integrations/**", "**/bin/**", "**/obj/**", "**/.*/**"]
    for kind in ("test_suites", "integrations"):
        for nested in project.manifest.get(kind, []):
            exclude.append(safe_pattern(nested.get("path") or kind + "/" + nested["id"]) + "/**")
    for pattern in dict.fromkeys(patterns):
        item = ET.SubElement(compile_items, "Compile", {"Include": source_pattern(pattern), "Exclude": ";".join(exclude)})
        ET.SubElement(item, "Link").text = "%(Identity)"
    packages = ET.SubElement(xml, "ItemGroup")
    ET.SubElement(packages, "GlobalAnalyzerConfigFiles", {
        "Include": "$(CthangoverRoot)ide/godot-runtime.globalconfig",
        "Condition": "Exists('$(CthangoverRoot)ide/godot-runtime.globalconfig')"})
    ET.SubElement(packages, "PackageReference", {"Include": "GodotSharp", "Version": godot_version})
    if not project.tests:
        ET.SubElement(packages, "PackageReference", {"Include": "Godot.SourceGenerators", "Version": godot_version,
                                                   "PrivateAssets": "all", "ReferenceOutputAssembly": "false"})
    refs = ET.SubElement(xml, "ItemGroup")
    add_project_reference(refs, "$(CthangoverRoot)Cthangover.csproj", "Exists('$(CthangoverRoot)Cthangover.csproj')")
    installed_reference(refs, "Cthangover", "$(CthangoverInstalledDirectory)Cthangover.dll",
                        "!Exists('$(CthangoverRoot)Cthangover.csproj')")
    # The installed core's third-party managed API is available without source/NuGet metadata.
    fallback = ET.SubElement(xml, "ItemGroup", {"Condition": "!Exists('$(CthangoverRoot)Cthangover.csproj')"})
    ET.SubElement(fallback, "Reference", {"Include": "$(CthangoverInstalledDirectory)*.dll",
                                       "Exclude": "$(CthangoverInstalledDirectory)Cthangover.dll;"
                                                  "$(CthangoverInstalledDirectory)GodotSharp*.dll"})
    for dependency in project.depends:
        if dependency in projects:
            target = projects[dependency].path
            same_repository = project.path.relative_to(root).parts[:2] == target.relative_to(root).parts[:2]
            if same_repository:
                path = "$(MSBuildThisFileDirectory)" + relative(target, project.directory)
            else:
                path = "$(CthangoverRoot)" + relative(target, root)
            add_project_reference(refs, path, "Exists('" + path + "')")
            binary = "$(CthangoverRoot).ide/bin/" + dependency + "/$(Configuration)/" + target_framework + "/" + dependency + ".dll"
            installed_reference(refs, dependency, binary, "!Exists('" + path + "') And Exists('" + binary + "')")
        else:
            # Optional dependencies may be absent. Required absent dependencies get an explicit build error below.
            continue
    for source in library_projects(project):
        source_path = relative(source, project.directory)
        add_project_reference(refs, source_path, "Exists('" + source_path + "')")
    for owner in reference_scope(project, projects):
        for source in library_projects(owner):
            assembly_name = ET.parse(source).getroot().findtext(".//AssemblyName") or source.stem
            source_path = relative(source, project.directory)
            selected = ET.SubElement(xml, "PropertyGroup", {"Condition": "Exists('" + source_path + "')"})
            for binary in (owner.directory / "dll").glob("*.dll"):
                if binary.stem.casefold() == assembly_name.casefold():
                    property_element(selected, "CthangoverSourceBinaryExcludes",
                                     "$(CthangoverSourceBinaryExcludes);" + relative(binary, project.directory))
    managed = ET.SubElement(xml, "ItemGroup")
    for owner in reference_scope(project, projects):
        prefix = relative(owner.directory, project.directory)
        prefix = "" if prefix == "." else prefix + "/"
        for pattern in ["dll/**/*.dll", *owner.manifest.get("references", [])]:
            if not pattern.lower().endswith(".dll"):
                raise ValueError("Managed reference must be a DLL pattern: " + pattern)
            attributes = {"Include": prefix + safe_pattern(pattern), "Exclude": "$(CthangoverSourceBinaryExcludes)"}
            item = ET.SubElement(managed, "Reference", attributes)
            ET.SubElement(item, "Private").text = "false"
    target = ET.SubElement(xml, "Target", {"Name": "ValidateModDependencies", "BeforeTargets": "ResolveReferences"})
    for raw in project.manifest.get("depends", []):
        dependency = dependency_id(raw)
        if dependency not in projects and not raw.strip().endswith("?"):
            ET.SubElement(target, "Error", {"Text": "Missing required mod dependency: " + dependency})
    ET.SubElement(xml, "Import", {"Project": "Sdk.targets", "Sdk": "Microsoft.NET.Sdk"})
    compiler_target = ET.SubElement(xml, "Target", {"Name": "UseRuntimeModGenerators", "BeforeTargets": "CoreCompile"})
    analyzer_items = ET.SubElement(compiler_target, "ItemGroup")
    analyzer_attributes = {"Remove": "@(Analyzer)"}
    if not project.tests:
        analyzer_attributes["Condition"] = "'%(Analyzer.Filename)' != 'Godot.SourceGenerators'"
    ET.SubElement(analyzer_items, "Analyzer", analyzer_attributes)
    if not project.tests:
        # Installed mods retain runtime diagnostic policy even when authoring tools were not shipped.
        target = ET.SubElement(xml, "Target", {"Name": "WriteRuntimeGodotDiagnostics", "BeforeTargets": "CoreCompile",
            "Condition": "!Exists('$(CthangoverRoot)ide/godot-runtime.globalconfig')"})
        ET.SubElement(target, "MakeDir", {"Directories": "$(IntermediateOutputPath)"})
        path = "$(IntermediateOutputPath)runtime.globalconfig"
        ET.SubElement(target, "WriteLinesToFile", {"File": path, "Overwrite": "true", "WriteOnlyWhenDifferent": "true",
            "Lines": "is_global = true;global_level = 100;dotnet_diagnostic.GD0001.severity = warning"})
        ET.SubElement(ET.SubElement(target, "ItemGroup"), "EditorConfigFiles", {"Include": path})
    # Runtime mod parsing defines no DEBUG/TRACE/TOOLS/framework symbols.
    final = ET.SubElement(xml, "PropertyGroup")
    property_element(final, "DefineConstants", "")
    ET.indent(xml, space="  ")
    return ET.tostring(xml, encoding="unicode") + "\n"


def project_guid(value: str) -> str:
    return "{" + str(uuid.uuid5(GUID_NAMESPACE, value)).upper() + "}"


def generate_solution(projects: dict[str, ModProject], root: Path) -> str:
    lines = ["Microsoft Visual Studio Solution File, Format Version 12.00", "# Visual Studio Version 17"]
    folders = ("engine", "tests", "mods", "mods_private", "source_projects")
    all_projects = []
    all_projects.append(("Cthangover", Path("Cthangover.csproj"), "engine"))
    for path in sorted((root / "tests").glob("*/*.csproj")):
        all_projects.append((path.stem, path.relative_to(root), "tests"))
    for project in sorted(projects.values(), key=project_sort_key):
        all_projects.append((project.id, project.path.relative_to(root), project.group))
    source_paths = set()
    for project in projects.values():
        source_paths.update(library_projects(project))
    for path in sorted(source_paths):
        all_projects.append((path.stem, path.relative_to(root), "source_projects"))
    for folder in folders:
        lines.extend([f'Project("{FOLDER_TYPE}") = "{folder}", "{folder}", "{project_guid("folder/" + folder)}"',
                      "EndProject"])
    for name, path, _ in all_projects:
        guid = project_guid(path.as_posix())
        windows_path = path.as_posix().replace("/", "\\")
        lines.extend([f'Project("{PROJECT_TYPE}") = "{name}", "{windows_path}", "{guid}"', "EndProject"])
    lines.extend(["Global", "\tGlobalSection(SolutionConfigurationPlatforms) = preSolution",
                  "\t\tDebug|Any CPU = Debug|Any CPU", "\t\tRelease|Any CPU = Release|Any CPU", "\tEndGlobalSection",
                  "\tGlobalSection(ProjectConfigurationPlatforms) = postSolution"])
    for _, path, _ in all_projects:
        guid = project_guid(path.as_posix())
        for config in ("Debug", "Release"):
            lines.extend([f"\t\t{guid}.{config}|Any CPU.ActiveCfg = {config}|Any CPU",
                          f"\t\t{guid}.{config}|Any CPU.Build.0 = {config}|Any CPU"])
    lines.extend(["\tEndGlobalSection", "\tGlobalSection(NestedProjects) = preSolution"])
    for _, path, group in all_projects:
        lines.append("\t\t" + project_guid(path.as_posix()) + " = " + project_guid("folder/" + group))
    lines.extend(["\tEndGlobalSection", "EndGlobal", ""])
    return "\n".join(lines)


def project_sort_key(project: ModProject) -> str:
    return project.id


def write_changed(path: Path, content: str) -> str:
    existed = path.exists()
    if existed and path.read_bytes() == content.encode("utf-8"):
        return "unchanged"
    if existed and path.suffix in (".csproj", ".props") and MARKER not in path.read_text(encoding="utf-8-sig"):
        raise ValueError("Refusing to replace a handwritten project: " + str(path))
    path.write_text(content, encoding="utf-8", newline="\n")
    return "updated" if existed else "added"


def update(root: Path) -> dict:
    projects = discover(root)
    core = ET.parse(root / "Cthangover.csproj").getroot()
    framework = core.findtext(".//TargetFramework")
    language = core.findtext(".//LangVersion")
    godot_version = core.attrib["Sdk"].split("/", 1)[1]
    outputs = {}
    for project in sorted(projects.values(), key=project_sort_key):
        outputs[project.path] = generate_project(project, projects, root, framework, language, godot_version)
        for source in library_projects(project):
            outputs[source.parent / "Directory.Build.props"] = source_output_props(project, root, source.parent)
    outputs[root / "Cthangover.All.sln"] = generate_solution(projects, root)
    statuses = {"added": [], "updated": [], "removed": [], "unchanged": []}
    # Only our marker grants ownership. A human project is never removed.
    for path in generated_candidates(root):
        if path not in outputs and MARKER in path.read_text(encoding="utf-8-sig"):
            path.unlink()
            statuses["removed"].append(relative(path, root))
    for path, content in outputs.items():
        status = write_changed(path, content)
        statuses[status].append(relative(path, root))
    statuses["projects"] = len(projects)
    return statuses


def generated_candidates(root: Path):
    for group in ("mods", "mods_private"):
        for directory, children, files in os.walk(root / group):
            children[:] = sorted(child for child in children if not child.startswith(".") and child not in ("bin", "obj"))
            for name in sorted(files):
                if name.endswith(".csproj") or name == "Directory.Build.props":
                    yield Path(directory) / name


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--json", type=Path)
    args = parser.parse_args()
    result = update(args.root.resolve())
    for status in ("added", "updated", "removed"):
        for path in result[status]:
            print(status + ": " + path)
    print(f"{result['projects']} mod/test assemblies; {len(result['unchanged'])} unchanged files")
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
